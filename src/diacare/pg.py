"""PostgreSQL cho Store: lớp kết nối nhỏ mô phỏng phần sqlite3 mà db.py dùng, để mã truy vấn giữ nguyên.

Bật bằng biến DIACARE_DATABASE_URL=postgresql://người_dùng:mật_khẩu@máy:5432/tên_db (hoặc truyền URL cho Store).
Không đặt thì vẫn dùng SQLite như cũ (Streamlit, CLI, test, Kaggle).

Khác biệt được xử lý ở đây:
- Tham số `?` của SQLite thành `%s`; dấu `%` có sẵn trong câu lệnh được nhân đôi.
- `cursor.lastrowid`: câu INSERT vào bảng có cột id được thêm `RETURNING id`.
- Schema: `INTEGER PRIMARY KEY AUTOINCREMENT` thành cột IDENTITY; `REAL` (float4 trong PostgreSQL, mất độ chính xác)
  thành `DOUBLE PRECISION`.
- Giá trị bool và số kiểu numpy được đổi sang int/float của Python (cột INTEGER của PostgreSQL không nhận bool).
- Kết nối ở chế độ autocommit: mỗi câu lệnh là một giao dịch, giống cách db.py gọi commit() sau mỗi lần ghi,
  và không để lại giao dịch mở khi Streamlit giữ kết nối lâu.
"""
import re

try:  # psycopg chỉ cần khi dùng PostgreSQL
    import psycopg
    from psycopg.rows import dict_row
    IntegrityError = psycopg.errors.IntegrityError
except ImportError:  # pragma: no cover - máy chỉ chạy SQLite
    psycopg = None

    class IntegrityError(Exception):
        pass

URL_PREFIXES = ("postgresql://", "postgres://")
# Bảng không có cột id tự tăng: INSERT không được thêm RETURNING id
_NO_ID_TABLES = {"targets"}
_INSERT_TABLE = re.compile(r"^\s*INSERT\s+INTO\s+(\w+)", re.IGNORECASE)


def is_url(path):
    return str(path).startswith(URL_PREFIXES)


def redact(url):
    """URL để in ra log: giấu mật khẩu."""
    return re.sub(r"(://[^:/@]+):[^@]*@", r"\1:***@", str(url))


def translate_schema(sql):
    """Schema SQLite thành schema PostgreSQL. Bỏ REFERENCES: SQLite của DiaCare chưa bao giờ bật kiểm tra khoá ngoại
    (PRAGMA foreign_keys tắt mặc định) nên hai backend phải cư xử giống nhau, và dữ liệu cũ chuyển sang được.
    Quyền sở hữu (hồ sơ thuộc tài khoản nào) được kiểm tra trong mã, không dựa vào khoá ngoại."""
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    sql = re.sub(r"\s+REFERENCES\s+\w+\s*\(\w+\)", "", sql)
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)


def _param(value):
    if isinstance(value, bool):
        return int(value)
    if type(value).__module__ == "numpy" and hasattr(value, "item"):
        return value.item()
    return value


class _Cursor:
    def __init__(self, cur, lastrowid=None):
        self._cur, self.lastrowid = cur, lastrowid

    @property
    def rowcount(self):
        return self._cur.rowcount

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur.fetchall() if self._cur.description else [])


class PgConnection:
    def __init__(self, url, connect_timeout=10):
        if psycopg is None:
            raise RuntimeError("Dùng PostgreSQL cần cài psycopg: pip install \"psycopg[binary]\"")
        self._conn = psycopg.connect(url, autocommit=True, row_factory=dict_row, connect_timeout=connect_timeout)

    def execute(self, sql, params=()):
        sql_pg = sql.replace("%", "%%").replace("?", "%s")
        m = _INSERT_TABLE.match(sql)
        returning = bool(m) and m.group(1).lower() not in _NO_ID_TABLES and "RETURNING" not in sql.upper()
        if returning:
            sql_pg += " RETURNING id"
        cur = self._conn.cursor()
        cur.execute(sql_pg, tuple(_param(p) for p in params) if params else None)
        lastrowid = None
        if returning:
            row = cur.fetchone()
            lastrowid = row["id"] if row else None
        return _Cursor(cur, lastrowid)

    def executescript(self, script):
        for stmt in script.split(";"):
            if stmt.strip():
                self._conn.execute(stmt)

    def commit(self):  # autocommit: mỗi câu lệnh đã được ghi
        pass

    def close(self):
        self._conn.close()

    def advisory_lock(self, key):
        self._conn.execute("SELECT pg_advisory_lock(hashtext(%s))", (key,))

    def advisory_unlock(self, key):
        self._conn.execute("SELECT pg_advisory_unlock(hashtext(%s))", (key,))

    def columns(self, table):
        rows = self._conn.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_name = %s"
            " AND table_schema = current_schema()", (table,)).fetchall()
        return {r["column_name"] for r in rows}
